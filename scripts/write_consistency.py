"""docs/consistency.md: the consistency checks behind the scorecard, every number read from results/.

  python scripts/write_consistency.py [--dir=results/bench_v3]   (after scripts/write_bench_v3.py wrote daily.csv)

Checks (each fails loudly if violated):
  1. the exact Benders master never loses to a heuristic (QAOA / QIEA) master on any day
  2. gap and critical downtime of a method-day come from the same run, and both downtime measures are shown
  3. the value of lost load is stated, and every gap is reported with and without it
  4. no gap is negative and no lower bound exceeds a feasible plan
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
NAMES = {"status_quo": "Status quo", "rule_based": "Rule-based battery controller", "ga": "Genetic algorithm",
         "pso": "Particle swarm optimisation", "per_building_mpc": "Per-building MPC", "central_mpc": "Central MPC",
         "central_mpc_comms_fail": "Central MPC, comms fail", "qgrid": "Q-Grid", "qgrid_comms_fail": "Q-Grid, comms fail",
         "optimum": "Best possible plan (reference)"}


def main(d: Path):
    cfg = yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))
    oc = cfg["outage_costs"]
    r = pd.read_csv(d / "daily.csv")
    if "regenerated" in r:          # previous results carried over for datasets not re-run are not checked here
        r = r[r.regenerated.astype(bool)]
    rv = r[r.dataset == "rvce"]
    L = ["# Consistency notes\n",
         f"_Generated by `scripts/write_consistency.py` from `{d.relative_to(ROOT)}/daily.csv` (one row per method, dataset and day, "
         "written by `scripts/write_bench_v3.py` from `runs.csv`) and `config.yaml`. Each section is a check that the script "
         "asserts; if one failed, this file would not be written._\n"]

    # 1 ---------------------------------------------------------------- exact vs heuristic masters
    piv = rv.pivot_table(index="day", columns="method", values="objective_rs")
    L.append("## 1. The exact master never loses to a QAOA master\n")
    have = [m for m in ("design_benders_exact", "design_benders_qaoa", "design_benders_qiea") if m in piv]
    if "design_benders_exact" in piv and len(have) > 1:
        ex = piv["design_benders_exact"]
        rows = []
        for m in have[1:]:
            diff = 100 * (piv[m] - ex) / ex
            lose = int((diff < -1e-6).sum())
            assert lose == 0, f"exact master lost to {m} on {lose} days"
            share = rv[rv.method == m].master_opt_share.mean()
            rows.append(f"| {m.split('_')[-1].upper()} master | {len(diff)} | {int((diff.abs() <= 1e-6).sum())} | {lose} | "
                        f"{100 * share:.1f} % |")
        L += ["In the earlier hybrid-Benders design the QAOA-master variant beat the exact-master variant on some days. Cause: "
              "the QAOA proposal was used unverified while the exact master was restricted to a trust region, so the two runs "
              "took different paths through the day and either could end up cheaper; the difference was path dependence, not "
              "a better quantum answer.",
              "",
              "Fix (`qgrid/v2/mpc.py`, `V2Config.verify_fallback`, test `test_exact_master_never_loses_to_a_heuristic_master`): "
              "every heuristic master proposal is checked against the exact master on the same cuts and trust region, and the "
              "exact proposal is the one used — the tiered fallback of CLAUDE.md. The heuristic's agreement rate is recorded. "
              "Result on the RVCE evaluation days of this run:",
              "",
              "| Design variant | days | same cost as exact master | days it beat the exact master | heuristic proposal = exact proposal |",
              "|---|---:|---:|---:|---:|", *rows, ""]
    else:
        L.append("The Benders design rows are not in this run.\n")

    # 2 ---------------------------------------------------------------- gap and downtime from the same run
    q = rv[rv.method == "qgrid"]
    L += ["## 2. Gap and critical downtime come from the same run\n",
          "Every figure of a method-day — gap to the best plan, certified gap, critical downtime, unserved energy, bill — is "
          "computed from one row of `runs.csv` (one simulated day of one method). The scorecard averages those rows; it never "
          "combines a gap from one run with a downtime from another.",
          "",
          f"Q-Grid on RVCE ({len(q)} days): gap {q.gap_pct.mean():.2f} %, critical downtime {q.critical_downtime_h.mean():.2f} h/day "
          f"(any shortfall), {q.critical_downtime_1pct_h.mean():.2f} h/day counting only slots with more than 1 % of critical "
          f"load unserved, critical energy unserved {q.critical_unserved_kwh.mean():.3f} kWh/day.",
          "- Strict downtime counts every 15-min slot with *any* unserved critical load (> 1e-6 kW), however small. A small "
          "gap next to a non-zero strict downtime means the shortfall is tiny in energy; the >1 % measure and the unserved "
          "energy show its size.",
          f"- At the critical value of lost load (Rs {oc['voll_critical_rs_kwh']}/kWh) Q-Grid's mean critical shortfall is worth "
          f"Rs {q.critical_unserved_kwh.mean() * oc['voll_critical_rs_kwh']:,.0f} per day.", ""]
    days_q = set(q.day)
    assert all(((rv.method == "qgrid") & (rv.day == dd)).sum() == 1 for dd in days_q), "one row per method-day"

    # 3 ---------------------------------------------------------------- VoLL
    L += ["## 3. Value of lost load (VoLL), and gaps with and without it\n",
          f"- VoLL inside every method's objective: non-critical load Rs {oc['voll_noncritical_rs_kwh']}/kWh, critical load "
          f"Rs {oc['voll_critical_rs_kwh']}/kWh.",
          "- Source: **ASSUMPTION** (`config.yaml` → `outage_costs`). No official Indian or BESCOM VoLL figure has been sourced; "
          "it is a modelling choice that makes shedding load never cheaper than serving it. The same values are used by every "
          "method on every day.",
          "- With VoLL = the objective the optimisers minimise (primary). Money only = energy + diesel + terminal value without "
          "VoLL; a method can look better on money alone by shedding more load.",
          "",
          "| Method (RVCE, mean over days) | gap with VoLL % | gap, money only % |", "|---|---:|---:|"]
    for m in NAMES:
        g = rv[rv.method == m]
        if len(g):
            L.append(f"| {NAMES[m]} | {g.gap_pct.mean():.2f} | {g.gap_novoll_pct.mean():.2f} |")
    L.append("")

    # 4 ---------------------------------------------------------------- reference and bounds
    main_m = r[r.method.isin(NAMES)]
    neg = int((main_m.gap_pct < -1e-9).sum())
    capped = int(main_m.drop_duplicates(["dataset", "day"]).LB_capped.sum()) if "LB_capped" in r else 0
    assert neg == 0
    L += ["## 4. Reference plan and certified bounds\n",
          "- The best plan for a day is the cheapest feasible plan known: the central MILP with perfect information, or a "
          "controller's realised plan where it is cheaper within the MILP's tolerance (relative gap 1e-4). No gap is negative.",
          f"- Certified gap uses the best proven lower bound (LP relaxation, MILP dual bound, Lagrangian bound with ADMM prices). "
          f"A valid bound can never exceed a feasible plan; on {capped} of {r[['dataset', 'day']].drop_duplicates().shape[0]} "
          "dataset-days the computed bound did (solver tolerance or a time-limited solve) and was capped at the best plan.", ""]
    # 5 ---------------------------------------------------------------- battery wear in every objective
    sys.path[:0] = [str(ROOT / "backend")]
    from qgrid.model import wear_rate
    wr = wear_rate(cfg)
    L += ["## 5. Battery wear is priced the same way everywhere\n",
          f"- Every optimiser (Q-Grid, per-building and central MPC, GA, PSO, the best possible plan, the certified bounds) prices "
          f"battery wear at Rs {wr:.2f} per kWh charged or discharged = battery cost / (2 × cycle life × depth of discharge) "
          "(`config.yaml` → `economics`, `battery_wear`; ASSUMPTIONS). The scored objective includes the same term, and the "
          "scorecard's degradation-cost column uses the same rate.",
          "- The earlier design rows (hybrid Benders, first prototype) predate this and do not price wear; they are design "
          "history under Verify, not scorecard rows.", ""]
    if "wear_rs" in r:
        g = r[r.method.isin(["qgrid", "optimum", "central_mpc"])]
        L.append("| Method (all datasets, mean) | battery cycles per day | wear Rs/day |\n|---|---:|---:|")
        for m, x in g.groupby("method"):
            L.append(f"| {NAMES[m]} | {x.battery_cycles.mean():.2f} | {x.wear_rs.mean():,.0f} |")
        L.append("")
    (ROOT / "docs" / "consistency.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote docs/consistency.md")


if __name__ == "__main__":
    dd = next((a.split("=", 1)[1] for a in sys.argv if a.startswith("--dir=")), "results/bench_v3")
    sys.exit(main(ROOT / dd))
