"""Adapt Q-Grid to another campus: OSM -> zones -> config -> pipeline -> replay. Nothing campus-specific is in code.

  python scripts/new_campus.py --name "PES University" --lat 12.935 --lon 77.535 [--bills path.csv] [--full]

Writes configs/campus_<slug>.yaml (copied from config.yaml with the new site/OSM name; zone rules, capacities and
assumptions are kept and should be reviewed), fetches the OSM layout and builds the processed data. With --full it
also runs the benchmark and replay (QGRID_CONFIG=configs/campus_<slug>.yaml) into results/campuses/<slug>/.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "backend"), str(ROOT)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--lat", type=float, required=True)
    ap.add_argument("--lon", type=float, required=True)
    ap.add_argument("--bills", default=None)
    ap.add_argument("--full", action="store_true")
    a = ap.parse_args()
    slug = re.sub(r"[^a-z0-9]+", "_", a.name.lower()).strip("_")
    cfg = yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))
    cfg["site"].update({"name": a.name, "lat": a.lat, "lon": a.lon})
    cfg["campus"].update({"display_name": a.name, "osm_name": a.name, "slug": slug})
    # RVCE-specific documented figures must not carry over: PV from roof area, floor areas from OSM, RVCE's
    # RV-University exclusion rule dropped (review zone rules and assets for the new campus)
    for k in ("existing_kwp", "existing_zone_kwp", "scenario", "status", "source"):
        cfg["campus"]["pv"].pop(k, None)
    cfg["campus"].pop("area_targets", None)
    cfg["campus"]["zone_rules"] = [r for r in cfg["campus"]["zone_rules"] if not r.get("rvce_only")]
    out = ROOT / "configs" / f"campus_{slug}.yaml"
    out.write_text("# Generated by scripts/new_campus.py — review zone rules, capacities and ASSUMPTIONS.\n" + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
    print("wrote", out.relative_to(ROOT))
    if a.bills:
        shutil.copy(a.bills, ROOT / "data" / "raw" / "rvce_bills.csv")
    env = {**os.environ, "QGRID_CONFIG": str(out.relative_to(ROOT)), "PYTHONPATH": f"{ROOT / 'backend'}:{ROOT}"}
    from qgrid.campus import build_layout
    os.environ["QGRID_CONFIG"] = env["QGRID_CONFIG"]
    lay = build_layout(cfg)
    print({z: round(v["footprint_m2"]) for z, v in lay["zones"].items()})
    if a.full:
        for s in ("-m qgrid.data", "scripts/run_benchmark.py", "scripts/make_replay.py"):
            subprocess.run([sys.executable, *s.split()], cwd=ROOT, env=env, check=True)
    else:
        print(f"next: QGRID_CONFIG={env['QGRID_CONFIG']} make data bench replay")


if __name__ == "__main__":
    main()
